# Writes the generated case files (cross products of functions and arguments)
# into cases/. The hand-written case files sit next to them.
#   python3 gen.py
import itertools
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def write(name, cases):
    with open(os.path.join(HERE, 'cases', name + '.lua'), 'w', encoding='ascii', newline='\n') as f:
        f.write('-- Generated by gen.py; do not edit.\n')
        for title, src in cases:
            f.write('--@@ %s\n%s\n' % (title, src))


NUMS = ['0', '-0.0', '1', '-1', '7', '3.14159', '-2.5', '0.5', '1.5', '2.5', '1e15', '1e100', '-1e-5',
        '2^31', '2^32', '2^53', '2^63', '-2^63', '2^64', '1/0', '-1/0', '0/0', '255', '65']
OTHER = ['"10"', '"0x10"', '" 12 "', '"abc"', '""', 'nil', 'true', '{}']


def fmt():
    cases = []
    convs = 'd i u c x X o e E f g G q s a A'.split()
    flags = ['', '-', '+', ' ', '#', '0']
    widths = ['', '8']
    precs = ['', '.0', '.3']
    vals = NUMS + OTHER
    for conv in convs:
        for v in vals:
            if v == '{}' and conv in 'sq':
                continue  # the text holds an address
            cases.append(('%%%s %s' % (conv, v), 'return string.format("%%%s", %s)' % (conv, v)))
        for fl, w, p in itertools.product(flags, widths, precs):
            spec = '%' + fl + w + p + conv
            for v in ['0', '-1', '3.14159', '255', '1e15', '"abc"']:
                cases.append(('%s %s' % (spec, v), 'return string.format("%s", %s)' % (spec, v)))
    for spec in ['%', '%5', '%-', '%t', '%10.3', '%123d', '%1.123d', '%#5.2x', '%%', '%5%', '%c%c%c']:
        cases.append(('bad %s' % spec, 'return string.format("%s", 65, 66, 67)' % spec))
    cases.append(('%s table', 'return (string.format("%s", {}):match("^table: ") ~= nil)'))
    cases.append(('missing arg', 'return string.format("%d %d", 1)'))
    cases.append(('extra args', 'return string.format("%d", 1, 2, 3)'))
    cases.append(('no format', 'return string.format()'))
    cases.append(('number format', 'return string.format(12)'))
    cases.append(('embedded zero', 'return string.format("a\\0b%sc", "x\\0y")'))
    cases.append(('%s tostring meta', 'return string.format("%s", setmetatable({}, {__tostring = function() return "T" end}))'))
    cases.append(('%s tostring meta non-string', 'return string.format("%s", setmetatable({}, {__tostring = function() return 1 end}))'))
    cases.append(('%q control chars', 'return string.format("%q", "\\r\\n\\t\\0\\1\\127\\200\\\\\\"")'))
    cases.append(('%q round trip', 'local s = "\\r\\n\\0\\1\\255" return load("return " .. string.format("%q", s))() == s'))
    cases.append(('%q number', 'return string.format("%q", 1/3)'))
    cases.append(('%5.1s', 'return string.format("[%5.1s]", "abc")'))
    write('format', cases)


def tonum():
    cases = []
    strs = ['"10"', '"  10  "', '"\\t5\\n"', '"0x10"', '"0X1F"', '"-0x10"', '"+0x2"', '"0x"', '"0x.8"', '"0x8."',
            '"0x1p4"', '"0x1P-1"', '"0x.1p4"', '"1e5"', '"1E+5"', '"1e-2"', '"1e"', '"1e+"', '".5"', '"5."', '"."',
            '"-.5"', '"+5"', '"- 5"', '"--5"', '"5-"', '"1 0"', '""', '" "', '"inf"', '"-inf"', '"nan"', '"NaN"',
            '"infinity"', '"0b101"', '"1_000"', '"5\\0"', '"9007199254740993"', '"1e400"', '"-1e400"', '"1e-400"',
            '"0x7fffffffffffffff"', '"0xffffffffffffffff"', '"0x10000000000000000"', '"00012"', '"1.5e3"',
            '"0x1.8"', '"  0x10  "', '"1,5"', '"\\v12\\f"']
    for s in strs:
        cases.append(('tonumber %s' % s, 'return tonumber(%s)' % s))
        cases.append(('arith %s' % s, 'return %s + 0' % s))
    bases = ['2', '8', '10', '16', '36', '1', '37', '0', '10.5', '"16"', 'nil']
    bstrs = ['"10"', '"ff"', '"FF"', '"zz"', '"-ff"', '" ff "', '"1.5"', '""', '"0x10"', '"8"', '"7fffffffffffffff"',
             '"11111111111111111111111111111111111111111111111111111111111111111"', '"+1"', '"- 1"']
    for b, s in itertools.product(bases, bstrs):
        cases.append(('tonumber %s base %s' % (s, b), 'return tonumber(%s, %s)' % (s, b)))
    for v in ['10', '1.5', 'nil', 'true', '{}', 'print']:
        cases.append(('tonumber value %s' % v, 'return tonumber(%s)' % v))
        cases.append(('tonumber value %s base 10' % v, 'return tonumber(%s, 10)' % v))
    cases.append(('tonumber no arg', 'return tonumber()'))
    cases.append(('tonumber 2 results', 'return select("#", tonumber("x"))'))
    write('tonumber', cases)


def tostr():
    cases = []
    vals = NUMS + ['0.1', '1/3', '100', '-100.5', '1e14', '1e16', '123456789012345', '1e-7', '2^53+1', '1e308*10',
                   '-(0/0)', '5e-324', '0.1+0.2', '10/2', '3.0', '-7/2']
    for v in vals:
        cases.append(('tostring %s' % v, 'return tostring(%s)' % v))
        cases.append(('concat %s' % v, 'return (%s) .. ""' % v))
        cases.append(('concat left %s' % v, 'return "x" .. (%s)' % v))
    for v in ['nil', 'true', 'false', '"s"']:
        cases.append(('tostring %s' % v, 'return tostring(%s)' % v))
    cases.append(('tostring no arg', 'return tostring()'))
    cases.append(('tostring __tostring string', 'return tostring(setmetatable({}, {__tostring = function() return "x" end}))'))
    cases.append(('tostring __tostring number', 'return tostring(setmetatable({}, {__tostring = function() return 42 end}))'))
    cases.append(('tostring __tostring table', 'return type(tostring(setmetatable({}, {__tostring = function() return {} end})))'))
    cases.append(('tostring __tostring nil', 'return tostring(setmetatable({}, {__tostring = function() end}))'))
    cases.append(('tostring __name ignored', 'return (tostring(setmetatable({}, {__name = "N"})):match("^table: ") ~= nil)'))
    cases.append(('tostring table prefix', 'return (tostring({}):match("^table: ") ~= nil)'))
    cases.append(('tostring function prefix', 'return (tostring(print):match("^function: ") ~= nil)'))
    cases.append(('tostring thread prefix', 'return (tostring(coroutine.create(print)):match("^thread: ") ~= nil)'))
    write('tostring', cases)


def strindex():
    cases = []
    idx = ['0', '1', '2', '-1', '-2', '-3', '3', '4', '10', '-10', '2.7', '-1.5', '2^31', '-2^31', '2^53', '1/0', '-1/0', '0/0', '"2"', 'nil']
    for i in idx:
        cases.append(('sub i=%s' % i, 'return string.sub("abc", %s)' % i))
        cases.append(('byte i=%s' % i, 'return string.byte("abc", %s)' % i))
        for j in ['-1', '2', '0', '10', '-10', '2^31', '1.5', 'nil']:
            cases.append(('sub i=%s j=%s' % (i, j), 'return string.sub("abc", %s, %s)' % (i, j)))
            cases.append(('byte i=%s j=%s' % (i, j), 'return string.byte("abc", %s, %s)' % (i, j)))
    for n in ['0', '1', '3', '-1', '2.5', '2.9', '"2"', 'nil', '1/0', '0/0']:
        cases.append(('rep n=%s' % n, 'return string.rep("ab", %s)' % n))
        cases.append(('rep sep n=%s' % n, 'return string.rep("ab", %s, ",")' % n))
        cases.append(('rep empty sep n=%s' % n, 'return string.rep("", %s, ".")' % n))
    for c in ['65', '0', '255', '256', '-1', '65.5', '65.9', '"66"', 'nil', '1/0', '0/0', '2^32+65']:
        cases.append(('char %s' % c, 'return string.char(%s)' % c))
    cases.append(('char none', 'return string.char()'))
    cases.append(('char many', 'return string.char(72, 105, 0, 33)'))
    cases.append(('byte none', 'return string.byte("")'))
    cases.append(('byte count', 'return select("#", string.byte("abcdef", 1, -1))'))
    cases.append(('len zeros', 'return #"a\\0b\\0", string.len("\\0\\0\\0")'))
    cases.append(('upper lower', 'return string.upper("abc\\200xyz"), string.lower("ABC\\200XYZ")'))
    cases.append(('reverse', 'return string.reverse("ab\\0c")'))
    cases.append(('method on number', 'local n = 12 return n:rep(2)'))
    cases.append(('method on literal', 'return ("x"):rep(3), #("abc"):upper()'))
    cases.append(('string index', 'return ("abc").len, ("abc").nope'))
    cases.append(('string index number', 'return ("abc")[1]'))
    cases.append(('string len meta', 'local mt = getmetatable("") mt.__len = function() return 99 end local n = #"abc" mt.__len = nil return n'))
    cases.append(('string arith coercion', 'return "10" + 1, "3" * "4", "2" ^ 2, -"2", "10" % 3, "0x10" + 0'))
    cases.append(('string arith bad', 'return "abc" + 1'))
    cases.append(('compare string number', 'return 1 < "2"'))
    cases.append(('eq string number', 'return 1 == "1"'))
    write('strings', cases)


def mathcases():
    cases = []
    vals = ['0', '-0.0', '1', '-1', '2.5', '-2.5', '0.5', '-0.5', '1e300', '1/0', '-1/0', '0/0', '2^53', '"3.7"', '"x"', 'nil']
    for fn in ['abs', 'ceil', 'floor', 'sqrt', 'exp', 'log', 'log10', 'sin', 'cos', 'tan', 'asin', 'acos', 'atan',
               'sinh', 'cosh', 'tanh', 'deg', 'rad', 'modf', 'frexp']:
        for v in vals:
            cases.append(('math.%s(%s)' % (fn, v), 'return math.%s(%s)' % (fn, v)))
    pairs = ['7, 3', '-7, 3', '7, -3', '-7, -3', '5.5, 2', '-5.5, 2', '1, 0', '0, 0', '-1, 0', '1/0, 2', '2, 1/0',
             '0/0, 1', '7, 0.5', '2^53, 3', '"7", "3"', '1, nil']
    for fn in ['fmod', 'pow', 'atan2', 'ldexp', 'max', 'min', 'log']:
        for p in pairs:
            cases.append(('math.%s(%s)' % (fn, p), 'return math.%s(%s)' % (fn, p)))
    for p in pairs:
        cases.append(('%% %s' % p, 'local a, b = %s return a %% b' % p))
        cases.append(('^ %s' % p, 'local a, b = %s return a ^ b' % p))
        cases.append(('/ %s' % p, 'local a, b = %s return a / b' % p))
    cases += [
        ('max none', 'return math.max()'), ('min none', 'return math.min()'),
        ('max mixed nan', 'return math.max(1, 0/0, 3), math.max(0/0, 1)'),
        ('min one', 'return math.min(4)'), ('max many', 'return math.max(3, 9, -1, 9.5)'),
        ('huge', 'return math.huge, -math.huge, math.huge == 1/0, math.huge > 1e308'),
        ('pi', 'return math.pi'),
        ('random range bad', 'return (pcall(math.random, 2, 1))'), ('random zero', 'return (pcall(math.random, 0))'),
        ('random float arg', 'math.randomseed(1) local r = math.random(3.5) return r >= 1 and r <= 3'),
        ('random too many', 'return (pcall(math.random, 1, 2, 3))'),
        ('random unit', 'math.randomseed(7) local r = math.random() return r >= 0 and r < 1'),
        ('randomseed none', 'return math.randomseed()'),
        ('tointeger absent', 'return math.tointeger, math.type, math.ult, math.maxinteger'),
        ('deprecated math present', 'return type(math.pow), type(math.ldexp), type(math.cosh)'),
        ('floor -0', 'return 1 / math.floor(-0.0), 1 / math.ceil(-0.5)'),
        ('modf negative', 'return math.modf(-3.7)'), ('modf inf', 'return math.modf(1/0)'),
        ('unary minus zero', 'return 1 / (-0), 1 / -(0)'),
        ('number literal hex float', 'return 0x1p4, 0x.8, 0xA.8p1, 0x10'),
        ('number literal big', 'return 0xffffffffffffffff, 1e309, 9007199254740993'),
        ('integer division by zero', 'return 1 % 0, -1 % 0, 0 % 0'),
        ('for near 2^53', 'local n = 0 for i = 2^53 - 4, 2^53 - 1 do n = n + 1 end return n'),
        ('for float step', 'local n = 0 for i = 0, 1, 0.1 do n = n + 1 end return n'),
        ('for step zero', 'local n = 0 for i = 1, 3, 0 do n = n + 1 if n > 5 then break end end return n'),
        ('for string bounds', 'local n = 0 for i = "1", "3" do n = n + 1 end return n'),
        ('for bad bound', 'for i = 1, "x" do end'),
        ('for nil step', 'for i = 1, 2, nil do end'),
    ]
    write('math', cases)


def selectcases():
    cases = []
    for n in ['1', '2', '3', '4', '-1', '-2', '-3', '-4', '0', '2.5', '"2"', '"#"', '"x"', 'nil', '1/0', '-2^31']:
        cases.append(('select %s' % n, 'return select(%s, "a", "b", "c")' % n))
    cases.append(('select # none', 'return select("#")'))
    cases.append(('select # nils', 'return select("#", nil, nil)'))
    cases.append(('select -1 none', 'return select(-1)'))
    cases.append(('select 1 none', 'return select(1)'))
    cases.append(('select 2 none', 'return select(2)'))
    write('select', cases)


if __name__ == '__main__':
    fmt()
