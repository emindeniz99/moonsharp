namespace MoonSharp.LuaCats
{
	/// <summary>
	/// Writes LuaCATS definitions (for lua-language-server) of what a configured <see cref="Script"/> can reach:
	/// every type registered with <see cref="UserData"/>, with the members its descriptor exposes; the globals
	/// the host set; and the standard library modules the script was created with.
	/// </summary>
	/// <remarks>
	/// The definitions are read from the same registry and descriptors that bind calls at run time, so they
	/// cannot list a member scripts cannot call. Create the script with the host's own setup code (the one
	/// that registers its types and sets its globals) and pass it here.
	/// </remarks>
	public static class LuaCatsGenerator
	{
		/// <summary>The second line of every generated file; <see cref="LuaCatsResult.WriteTo"/> removes only
		/// files that start with it.</summary>
		public const string Banner = "-- Generated by MoonSharp.LuaCats from the registered C# API. Do not edit.";

		/// <summary>Generates the definitions for a configured script.</summary>
		public static LuaCatsResult Generate(Script script)
		{
			if (script == null)
				throw new ArgumentNullException("script");

			return new Emitter(script).Run();
		}
	}

	internal sealed class Emitter
	{
		sealed class ClassInfo
		{
			public Type Type;
			public string Name;
			public IUserDataDescriptor Descriptor; // null for a type scripts can only pass, never read
			public string Body;
		}

		static readonly string[] s_LuaKeywords = { "and", "break", "do", "else", "elseif", "end", "false", "for",
			"function", "goto", "if", "in", "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while" };

		static readonly Dictionary<string, string> s_Operators = new Dictionary<string, string>
		{
			{ "op_Addition", "add" }, { "op_Subtraction", "sub" }, { "op_Multiply", "mul" },
			{ "op_Division", "div" }, { "op_Modulus", "mod" },
		};

		static readonly HashSet<Type> s_Numeric = new HashSet<Type>
		{
			typeof(sbyte), typeof(byte), typeof(short), typeof(ushort), typeof(int), typeof(uint),
			typeof(long), typeof(ulong), typeof(float), typeof(double), typeof(decimal),
		};

		readonly Script m_Script;
		readonly Dictionary<Type, ClassInfo> m_Classes = new Dictionary<Type, ClassInfo>();
		readonly Queue<ClassInfo> m_Pending = new Queue<ClassInfo>();
		readonly SortedSet<string> m_Warnings = new SortedSet<string>(StringComparer.Ordinal);
		List<string> m_ExtensionNames;
		string m_Context = "";

		/// <summary>int64 and uint64 values can reach scripts: the module is loaded or CLR long/ulong convert exactly.</summary>
		internal readonly bool Int64;

		public Emitter(Script script)
		{
			m_Script = script;
			Int64 = script.Globals.Get("int64").IsNotNil() || script.Options.ExactInt64Interop;
		}

		public LuaCatsResult Run()
		{
			var files = new SortedDictionary<string, string>(StringComparer.Ordinal);

			foreach (Type t in UserData.GetRegisteredTypes())
			{
				// MoonSharp's own helper types (event facades, iterators, JSON markers) are not host API.
				if (t.Assembly == typeof(Script).Assembly || t.IsGenericTypeDefinition)
					continue;

				IUserDataDescriptor d = UserData.GetDescriptorForType(t, false);
				if (d != null)
					ClassOf(d);
			}

			var stdlib = new StandardLibrary(m_Script, this);
			files["_stdlib.lua"] = Header() + stdlib.Emit();
			files["_globals.lua"] = Header() + EmitGlobals(stdlib);

			while (m_Pending.Count > 0)
			{
				ClassInfo c = m_Pending.Dequeue();
				c.Body = (c.Descriptor != null) ? EmitMembers(c) : null;
			}

			foreach (ClassInfo c in m_Classes.Values)
				files[c.Name + ".lua"] = Header() + EmitClass(c);

			return new LuaCatsResult(files, m_Warnings.ToList(), stdlib.DisabledBuiltins);
		}

		static string Header()
		{
			return "---@meta\n" + LuaCatsGenerator.Banner + "\n\n";
		}

		internal void Warn(string message)
		{
			m_Warnings.Add(m_Context + message);
		}

		// ---- classes ----------------------------------------------------------------------------------------

		ClassInfo ClassOf(IUserDataDescriptor d)
		{
			ClassInfo c;

			if (!m_Classes.TryGetValue(d.Type, out c))
			{
				c = new ClassInfo { Type = d.Type, Name = TypeName(d.Type), Descriptor = d };
				m_Classes.Add(d.Type, c);
				m_Pending.Enqueue(c);
			}

			return c;
		}

		ClassInfo StubOf(Type t)
		{
			ClassInfo c;

			if (!m_Classes.TryGetValue(t, out c))
			{
				c = new ClassInfo { Type = t, Name = TypeName(t) };
				m_Classes.Add(t, c);
			}

			return c;
		}

		internal static string TypeName(Type t)
		{
			if (t.IsArray)
				return TypeName(t.GetElementType()) + "_Array";

			if (t.IsGenericType && !t.IsGenericTypeDefinition)
				return TypeName(t.GetGenericTypeDefinition()) + "_" +
					string.Join("_", t.GetGenericArguments().Select(a => TypeName(a).Replace('.', '_')).ToArray());

			return Regex.Replace((t.FullName ?? t.Name).Replace('+', '.'), "`[0-9]+", "");
		}

		/// <summary>The C# spelling of a type, for messages.</summary>
		static string Display(Type t)
		{
			if (t.IsGenericType)
				return Regex.Replace(t.GetGenericTypeDefinition().FullName, "`[0-9]+", "").Replace('+', '.') +
					"<" + string.Join(", ", t.GetGenericArguments().Select(Display).ToArray()) + ">";

			return (t.FullName ?? t.Name).Replace('+', '.');
		}

		static string LocalName(ClassInfo c)
		{
			return c.Name.Replace('.', '_');
		}

		string EmitClass(ClassInfo c)
		{
			var sb = new StringBuilder();
			var parents = new List<string>();

			for (Type b = c.Type.BaseType; b != null; b = b.BaseType)
			{
				ClassInfo p;
				if (m_Classes.TryGetValue(b, out p))
				{
					parents.Add(p.Name);
					break;
				}
			}

			foreach (Type i in c.Type.GetInterfaces())
			{
				ClassInfo p;
				if (m_Classes.TryGetValue(i, out p))
					parents.Add(p.Name);
			}

			var composite = c.Descriptor as CompositeUserDataDescriptor;
			if (composite != null)
				parents.AddRange(composite.Descriptors.Select(d => m_Classes[d.Type].Name));

			parents = parents.Distinct().OrderBy(n => n, StringComparer.Ordinal).ToList();

			if (c.Descriptor == null)
				sb.Append("---Not registered with MoonSharp: a script can pass only nil or a userdata of a registered type that derives from it.\n");

			sb.Append("---@class ").Append(c.Name);
			if (parents.Count > 0)
				sb.Append(" : ").Append(string.Join(", ", parents.ToArray()));
			sb.Append('\n');

			if (c.Body != null)
				sb.Append(c.Body);

			return sb.ToString();
		}

		// ---- members ----------------------------------------------------------------------------------------

		string EmitMembers(ClassInfo c)
		{
			IUserDataDescriptor d = c.Descriptor;

			var proxy = d as ProxyUserDataDescriptor;
			if (proxy != null)
				d = proxy.InnerDescriptor;

			var dispatching = d as DispatchingUserDataDescriptor;

			if (dispatching == null)
			{
				var composite = d as CompositeUserDataDescriptor;

				if (composite != null)
				{
					foreach (IUserDataDescriptor inner in composite.Descriptors)
						ClassOf(inner);

					return null;
				}

				Warn(string.Format("{0}: members of a {1} are not known; declared as [string] any", c.Name, d.GetType().Name));
				return "---@field [string] any\n";
			}

			var fields = new List<string>();
			var ops = new List<string>();
			var functions = new List<string>();
			string self = LocalName(c);

			foreach (var pair in dispatching.Members.OrderBy(p => p.Key, StringComparer.Ordinal))
			{
				string name = pair.Key;
				IMemberDescriptor m = pair.Value;
				m_Context = c.Name + "." + name + ": ";
				var overloaded = m as OverloadedMethodMemberDescriptor;

				if (overloaded != null)
				{
					IOverloadableMemberDescriptor[] overloads = overloaded.Overloads;

					// Members added for extension methods have no overloads of their own.
					if (overloads.Length == 0)
						continue;

					string op;
					if (s_Operators.TryGetValue(name, out op))
						ops.AddRange(BinaryOperators(c, op, overloads));
					else if (name == "op_UnaryNegation")
						ops.AddRange(overloads.Select(o => "---@operator unm: " + (Out(ReturnType(o)) ?? "nil")));
					else if (name == "get_Item")
						fields.AddRange(Indexers(overloads));
					else if (name == "__new")
						functions.Add(Function(c, self, "__new", overloads, false));
					else if (name.StartsWith("op_") || name.StartsWith("__") || overloads.All(IsAccessor))
						continue; // other operators, conversions (__toInt32...) and property or event accessors
					else if (IsIdentifier(name))
						functions.Add(Function(c, self, name, overloads, false));
					else
						Warn("not a Lua identifier, not declared");

					continue;
				}

				if (!IsIdentifier(name))
				{
					Warn("not a Lua identifier, not declared");
					continue;
				}

				var dynValue = m as DynValueMemberDescriptor;
				if (dynValue != null && dynValue.Value.Type == DataType.ClrFunction && d is StandardEnumUserDataDescriptor)
				{
					if (!name.StartsWith("__"))
						functions.Add(EnumFunction(c, self, name));
					continue;
				}

				string type = MemberType(c, m);
				fields.Add(string.Format("---@field {0} {1}{2}", name, type, Notes(m)));
			}

			m_Context = c.Name + ": ";
			string len = LengthOperator(c, dispatching);
			if (len != null)
				ops.Add(len);

			foreach (string meta in dispatching.MetaMembers.Select(p => p.Key))
				Warn(string.Format("metamethod {0} (from MoonSharpUserDataMetamethod) is not declared", meta));

			functions.AddRange(ExtensionMethods(c, self, dispatching));
			m_Context = "";

			var sb = new StringBuilder();
			foreach (string f in fields.Concat(ops.Distinct()))
				sb.Append(f).Append('\n');
			sb.Append("local ").Append(self).Append(" = {}\n");
			foreach (string f in functions)
				sb.Append('\n').Append(f);
			return sb.ToString();
		}

		static bool IsAccessor(IOverloadableMemberDescriptor o)
		{
			var m = o as MethodMemberDescriptor;
			if (m == null || !m.MethodInfo.IsSpecialName)
				return false;

			string n = m.MethodInfo.Name;
			return n.StartsWith("get_") || n.StartsWith("set_") || n.StartsWith("add_") || n.StartsWith("remove_");
		}

		string MemberType(ClassInfo c, IMemberDescriptor m)
		{
			var property = m as PropertyMemberDescriptor;
			if (property != null)
				return Out(property.PropertyInfo.PropertyType);

			var field = m as FieldMemberDescriptor;
			if (field != null)
				return Out(field.FieldInfo.FieldType);

			var ev = m as EventMemberDescriptor;
			if (ev != null)
			{
				string handler = Function(ev.EventInfo.EventHandlerType, true);
				return string.Format("{{ add: fun(handler: {0}), remove: fun(handler: {0}) }}", handler);
			}

			var hardwired = m as HardwiredMemberDescriptor;
			if (hardwired != null)
				return Out(hardwired.MemberType);

			var dynValue = m as DynValueMemberDescriptor;
			if (dynValue != null)
				return ValueType(dynValue.Value);

			Warn(string.Format("member kind {0} is not known; declared as any", m.GetType().Name));
			return "any";
		}

		static string Notes(IMemberDescriptor m)
		{
			var notes = new List<string>();

			if (m.IsStatic && !(m is DynValueMemberDescriptor))
				notes.Add("static");

			bool read = (m.MemberAccess & MemberDescriptorAccess.CanRead) != 0;
			bool write = (m.MemberAccess & MemberDescriptorAccess.CanWrite) != 0;

			if (!(m is EventMemberDescriptor))
			{
				if (read && !write)
					notes.Add("read-only");
				else if (write && !read)
					notes.Add("write-only");
			}

			return notes.Count == 0 ? "" : " " + string.Join(", ", notes.ToArray());
		}

		string ValueType(DynValue v)
		{
			switch (v.Type)
			{
				case DataType.Boolean: return "boolean";
				case DataType.Number: return "number";
				case DataType.String: return "string";
				case DataType.Table: return "table";
				case DataType.Function:
				case DataType.ClrFunction: return "function";
				case DataType.UserData:
					return (v.UserData.Descriptor != null) ? ClassOf(v.UserData.Descriptor).Name : "userdata";
				default: return "any";
			}
		}

		IEnumerable<string> BinaryOperators(ClassInfo c, string op, IEnumerable<IOverloadableMemberDescriptor> overloads)
		{
			foreach (IOverloadableMemberDescriptor o in overloads)
			{
				ParameterDescriptor[] p = o.Parameters;

				// LuaCATS declares an operator on its left operand's class.
				if (p.Length == 2 && p[0].Type.IsAssignableFrom(c.Type))
					yield return string.Format("---@operator {0}({1}): {2}", op, In(p[1].Type), Out(ReturnType(o)) ?? "nil");
			}
		}

		string LengthOperator(ClassInfo c, DispatchingUserDataDescriptor d)
		{
			// The same lookup DispatchingUserDataDescriptor uses for __len.
			foreach (string name in new[] { "Length", "Count" })
			{
				IMemberDescriptor m = d.FindMember(name);

				if (m != null && (m.MemberAccess & MemberDescriptorAccess.CanRead) != 0
					&& (m.MemberAccess & MemberDescriptorAccess.CanExecute) == 0)
				{
					return "---@operator len: " + MemberType(c, m);
				}
			}

			return null;
		}

		IEnumerable<string> Indexers(IEnumerable<IOverloadableMemberDescriptor> overloads)
		{
			foreach (IOverloadableMemberDescriptor o in overloads)
			{
				Type[] keys = o.Parameters.Where(p => !IsInjected(p.Type)).Select(p => p.Type).ToArray();

				if (keys.Length == 1)
					yield return string.Format("---@field [{0}] {1}", In(keys[0]), Out(ReturnType(o)) ?? "nil");
			}
		}

		string EnumFunction(ClassInfo c, string self, string name)
		{
			string value = c.Name + "|number";

			switch (name)
			{
				case "flagsNot":
					return string.Format("---@param a {0}\n---@return {1}\nfunction {2}.{3}(a) end\n", value, c.Name, self, name);
				case "hasAll":
				case "hasAny":
					return string.Format("---@param a {0}\n---@param b {0}\n---@return boolean\nfunction {1}.{2}(a, b) end\n", value, self, name);
				default:
					return string.Format("---@param a {0}\n---@param b {0}\n---@return {1}\nfunction {2}.{3}(a, b) end\n", value, c.Name, self, name);
			}
		}

		IEnumerable<string> ExtensionMethods(ClassInfo c, string self, DispatchingUserDataDescriptor d)
		{
			foreach (string name in ExtensionNames())
			{
				// A member of the type wins over an extension method with the same name.
				if (d.HasMember(name))
					continue;

				List<IOverloadableMemberDescriptor> methods = UserData.GetExtensionMethodsByNameAndType(name, c.Type);

				if (methods != null && methods.Count > 0)
					yield return Function(c, self, name, methods, true);
			}
		}

		/// <summary>
		/// Names of extension methods in the loaded assemblies. Only the ones the registry returns for a type
		/// (registered with <see cref="UserData.RegisterExtensionType"/>) are declared.
		/// </summary>
		List<string> ExtensionNames()
		{
			if (m_ExtensionNames != null)
				return m_ExtensionNames;

			var names = new SortedSet<string>(StringComparer.Ordinal);

			foreach (Assembly asm in AppDomain.CurrentDomain.GetAssemblies())
			{
				if (asm.IsDynamic)
					continue;

				Type[] types;
				try { types = asm.GetTypes(); }
				catch (ReflectionTypeLoadException ex) { types = ex.Types.Where(t => t != null).ToArray(); }

				foreach (Type t in types)
				{
					if (!t.IsSealed || !t.IsAbstract || !t.IsDefined(typeof(ExtensionAttribute), false))
						continue;

					foreach (MethodInfo mi in t.GetMethods(BindingFlags.Public | BindingFlags.Static))
						if (mi.IsDefined(typeof(ExtensionAttribute), false))
							names.Add(mi.Name);
				}
			}

			m_ExtensionNames = names.ToList();
			return m_ExtensionNames;
		}

		// ---- functions --------------------------------------------------------------------------------------

		sealed class Signature
		{
			public bool IsStatic;
			public List<KeyValuePair<string, string>> Params = new List<KeyValuePair<string, string>>();  // name ("x", "x?" or "..."), type
			public List<KeyValuePair<string, string>> Returns = new List<KeyValuePair<string, string>>(); // type, name or null
		}

		string Function(ClassInfo c, string self, string name, IEnumerable<IOverloadableMemberDescriptor> overloads, bool asExtension)
		{
			List<Signature> sigs = overloads
				.Select(o => Sign(c, o, asExtension))
				.OrderBy(s => s.Params.Count)
				.ThenBy(s => Fun(c, s), StringComparer.Ordinal)
				.ToList();

			Signature main = sigs[0];
			var sb = new StringBuilder();

			foreach (var p in main.Params)
				sb.Append("---@param ").Append(p.Key).Append(' ').Append(p.Value).Append('\n');
			foreach (var r in main.Returns)
				sb.Append("---@return ").Append(r.Key).Append(r.Value != null ? " " + r.Value : "").Append('\n');
			foreach (string fun in sigs.Skip(1).Select(s => Fun(c, s)).Distinct().Where(f => f != Fun(c, main)))
				sb.Append("---@overload ").Append(fun).Append('\n');

			sb.Append("function ").Append(self).Append(main.IsStatic ? "." : ":").Append(name).Append('(')
				.Append(string.Join(", ", main.Params.Select(p => p.Key.TrimEnd('?')).ToArray()))
				.Append(") end\n");

			return sb.ToString();
		}

		static string Fun(ClassInfo c, Signature s)
		{
			var ps = new List<string>();

			if (!s.IsStatic)
				ps.Add("self: " + c.Name);

			foreach (var p in s.Params)
				ps.Add(p.Key + ": " + p.Value);

			string fun = "fun(" + string.Join(", ", ps.ToArray()) + ")";

			if (s.Returns.Count > 0)
				fun += ": " + string.Join(", ", s.Returns.Select(r => r.Key).ToArray());

			return fun;
		}

		Signature Sign(ClassInfo c, IOverloadableMemberDescriptor o, bool asExtension)
		{
			var sig = new Signature { IsStatic = o.IsStatic && !asExtension };
			var extra = new List<KeyValuePair<string, string>>();
			ParameterDescriptor[] ps = o.Parameters;

			for (int i = 0; i < ps.Length; i++)
			{
				ParameterDescriptor p = ps[i];
				string name = ParamName(p.Name, i);

				if (asExtension && i == 0)
					continue;

				if (p.Type == typeof(CallbackArguments))
				{
					sig.Params.Add(new KeyValuePair<string, string>("...", "any"));
					break;
				}

				if (IsInjected(p.Type))
					continue;

				if (p.IsOut)
				{
					extra.Add(new KeyValuePair<string, string>(Out(p.Type), name));
					continue;
				}

				if (p.IsRef)
					extra.Add(new KeyValuePair<string, string>(Out(p.Type), name));

				if (p.IsVarArgs)
					sig.Params.Add(new KeyValuePair<string, string>("...", In(p.Type.GetElementType())));
				else
					sig.Params.Add(new KeyValuePair<string, string>(name + (p.HasDefaultValue ? "?" : ""), In(p.Type)));
			}

			Type ret = ReturnType(o);
			string retType = IsConstructor(o) ? c.Name : Out(ret);

			if (retType != null)
				sig.Returns.Add(new KeyValuePair<string, string>(retType, null));
			else if (extra.Count > 0)
				sig.Returns.Add(new KeyValuePair<string, string>("nil", null));

			sig.Returns.AddRange(extra);
			return sig;
		}

		static bool IsConstructor(IOverloadableMemberDescriptor o)
		{
			var m = o as MethodMemberDescriptor;
			return (m != null && m.IsConstructor) || o is ValueTypeDefaultCtorMemberDescriptor;
		}

		static Type ReturnType(IOverloadableMemberDescriptor o)
		{
			var m = o as MethodMemberDescriptor;
			if (m != null && !m.IsConstructor)
				return ((MethodInfo)m.MethodInfo).ReturnType;

			return typeof(object);
		}

		static bool IsInjected(Type t)
		{
			// FunctionMemberDescriptorBase.BuildArgumentList fills these itself.
			return t == typeof(Script) || t == typeof(ScriptExecutionContext);
		}

		static string ParamName(string name, int index)
		{
			if (string.IsNullOrEmpty(name))
				return "arg" + index;

			return IsIdentifier(name) ? name : name + "_";
		}

		internal static bool IsIdentifier(string name)
		{
			return Regex.IsMatch(name, "^[A-Za-z_][A-Za-z0-9_]*$") && Array.IndexOf(s_LuaKeywords, name) < 0;
		}

		/// <summary>A delegate as a Lua function type. With <paramref name="calledByClr"/>, the CLR calls a Lua
		/// function of this type (an event handler); otherwise a script calls a CLR delegate.</summary>
		string Function(Type delegateType, bool calledByClr)
		{
			MethodInfo invoke = delegateType.GetMethod("Invoke");
			if (invoke == null)
				return "function";

			ParameterInfo[] ps = invoke.GetParameters();
			var args = new List<string>();

			for (int i = 0; i < ps.Length; i++)
				args.Add(ParamName(ps[i].Name, i) + ": " + (calledByClr ? Out(ps[i].ParameterType) : In(ps[i].ParameterType)));

			string fun = "fun(" + string.Join(", ", args.ToArray()) + ")";

			if (!calledByClr && invoke.ReturnType != typeof(void))
				fun += ": " + Out(invoke.ReturnType);

			return fun;
		}

		// ---- type mapping -----------------------------------------------------------------------------------

		/// <summary>The Lua type of a CLR value read by a script (ClrToScriptConversions.ObjectToDynValue);
		/// null for void.</summary>
		internal string Out(Type t)
		{
			if (t == typeof(void))
				return null;
			if (t.IsByRef)
				t = t.GetElementType();
			if (t == typeof(DynValue) || t == typeof(object))
				return "any";
			if (Script.GlobalOptions.CustomConverters.GetClrToScriptCustomConversion(t) != null)
				return "any";

			Type nullable = Nullable.GetUnderlyingType(t);
			if (nullable != null)
				return Optional(Out(nullable));

			if (t == typeof(bool))
				return "boolean";
			if (t == typeof(string) || t == typeof(char) || t == typeof(StringBuilder))
				return "string";
			if (t == typeof(long) && m_Script.Options.ExactInt64Interop)
				return "int64";
			if (t == typeof(ulong) && m_Script.Options.ExactInt64Interop)
				return "uint64";
			if (s_Numeric.Contains(t))
				return "number";
			if (t == typeof(Table))
				return "table";
			if (t == typeof(Closure) || t == typeof(CallbackFunction))
				return "function";
			if (t == typeof(LuaInt64))
				return "int64";
			if (t == typeof(LuaUInt64))
				return "uint64";

			if (t == typeof(Type))
				return "any"; // the static userdata of that type

			IUserDataDescriptor d = UserData.GetDescriptorForType(t, true);
			if (d != null)
				return ClassOf(d).Name;

			if (t.IsEnum)
				return "number";
			if (typeof(Delegate).IsAssignableFrom(t))
				return Function(t, false);
			if (typeof(IList).IsAssignableFrom(t) || IsGeneric(t, typeof(IList<>), typeof(IReadOnlyList<>)))
				return ArrayOf(Out(ElementType(t)));

			Type[] kv = DictionaryTypes(t);
			if (kv != null)
				return string.Format("table<{0}, {1}>", Out(kv[0]), Out(kv[1]));

			if (typeof(IEnumerable).IsAssignableFrom(t) || typeof(IEnumerator).IsAssignableFrom(t))
				return "fun(): " + Out(ElementType(t));

			Warn(string.Format("{0} is not registered: a script that reads one gets an error (\"cannot convert clr type\"); declared as any", Display(t)));
			return "any";
		}

		/// <summary>The Lua types a script can pass for a CLR parameter (ScriptToClrConversions).</summary>
		internal string In(Type t)
		{
			if (t.IsByRef)
				t = t.GetElementType();
			if (t == typeof(DynValue) || t == typeof(object))
				return "any";

			foreach (DataType dt in Enum.GetValues(typeof(DataType)))
				if (Script.GlobalOptions.CustomConverters.GetScriptToClrCustomConversion(dt, t) != null)
					return "any";

			Type nullable = Nullable.GetUnderlyingType(t);
			if (nullable != null)
				return Optional(In(nullable));

			if (t == typeof(bool))
				return "boolean";
			if (t == typeof(string) || t == typeof(char) || t == typeof(StringBuilder))
				return "string";
			if ((t == typeof(long) || t == typeof(ulong)) && Int64)
				return "number|int64|uint64";
			if (s_Numeric.Contains(t))
				return "number";
			if (t == typeof(Table))
				return "table";
			if (t == typeof(Closure) || t == typeof(ScriptFunctionDelegate) || t == typeof(CallbackFunction))
				return "function";
			if (t == typeof(LuaInt64))
				return "int64";
			if (t == typeof(LuaUInt64))
				return "uint64";

			IUserDataDescriptor d = UserData.GetDescriptorForType(t, true);
			string userdata = (d != null) ? ClassOf(d).Name : null;

			if (t.IsEnum)
				return (userdata != null) ? userdata + "|number" : "number";

			string table = TableType(t);
			if (table != null)
				return (userdata != null) ? userdata + "|" + table : table;

			if (userdata != null)
				return userdata;

			// Scripts can pass a userdata of a registered type that derives from t, and nothing else.
			if (typeof(Delegate).IsAssignableFrom(t))
				Warn(string.Format("{0}: a script cannot pass a function for this delegate type (MoonSharp converts functions only to Closure and ScriptFunctionDelegate, or through a custom converter)", Display(t)));

			return StubOf(t).Name;
		}

		/// <summary>The table a script can pass for a CLR collection (TableConversions.ConvertTableToType).</summary>
		string TableType(Type t)
		{
			if (t.IsAssignableFrom(typeof(Dictionary<object, object>)) || t.IsAssignableFrom(typeof(Dictionary<DynValue, DynValue>)))
				return "table";
			if (t.IsAssignableFrom(typeof(List<object>)) || t.IsAssignableFrom(typeof(List<DynValue>))
				|| t.IsAssignableFrom(typeof(object[])) || t.IsAssignableFrom(typeof(DynValue[])))
				return "any[]";

			if (t.IsGenericType)
			{
				Type def = t.GetGenericTypeDefinition();
				Type[] args = t.GetGenericArguments();

				if (def == typeof(List<>) || def == typeof(IList<>) || def == typeof(ICollection<>) || def == typeof(IEnumerable<>))
					return ArrayOf(In(args[0]));
				if (def == typeof(Dictionary<,>) || def == typeof(IDictionary<,>))
					return string.Format("table<{0}, {1}>", In(args[0]), In(args[1]));
			}

			if (t.IsArray && t.GetArrayRank() == 1)
				return ArrayOf(In(t.GetElementType()));

			return null;
		}

		static bool IsGeneric(Type t, params Type[] definitions)
		{
			return t.IsGenericType && definitions.Contains(t.GetGenericTypeDefinition());
		}

		static Type ElementType(Type t)
		{
			if (t.IsArray)
				return t.GetElementType();

			foreach (Type i in new[] { t }.Concat(t.GetInterfaces()))
				if (IsGeneric(i, typeof(IEnumerable<>)))
					return i.GetGenericArguments()[0];

			return typeof(object);
		}

		static Type[] DictionaryTypes(Type t)
		{
			foreach (Type i in new[] { t }.Concat(t.GetInterfaces()))
				if (IsGeneric(i, typeof(IDictionary<,>), typeof(IReadOnlyDictionary<,>)))
					return i.GetGenericArguments();

			return typeof(IDictionary).IsAssignableFrom(t) ? new[] { typeof(object), typeof(object) } : null;
		}

		static bool IsSimple(string type)
		{
			return type.IndexOfAny(new[] { '|', ' ', '(' }) < 0;
		}

		static string ArrayOf(string type)
		{
			return IsSimple(type) ? type + "[]" : "(" + type + ")[]";
		}

		static string Optional(string type)
		{
			return IsSimple(type) ? type + "?" : type + "|nil";
		}

		// ---- globals ----------------------------------------------------------------------------------------

		string EmitGlobals(StandardLibrary stdlib)
		{
			var sb = new StringBuilder();

			foreach (var pair in m_Script.Globals.Pairs
				.Where(p => p.Key.Type == DataType.String)
				.OrderBy(p => p.Key.String, StringComparer.Ordinal))
			{
				string name = pair.Key.String;

				// Names starting with "__" are MoonSharp internals (such as __require_clr_impl).
				if (stdlib.Handles(name) || name.StartsWith("__"))
					continue;

				if (!IsIdentifier(name))
				{
					Warn(string.Format("global \"{0}\": not a Lua identifier, not declared", name));
					continue;
				}

				m_Context = "global " + name + ": ";
				EmitValue(sb, name, pair.Value, new HashSet<Table>());
				m_Context = "";
			}

			return sb.ToString();
		}

		internal void EmitValue(StringBuilder sb, string path, DynValue v, HashSet<Table> seen)
		{
			switch (v.Type)
			{
				case DataType.Nil:
				case DataType.Void:
					return;
				case DataType.Function:
				case DataType.ClrFunction:
					sb.Append("---@param ... any\n---@return any ...\nfunction ").Append(path).Append("(...) end\n\n");
					return;
				case DataType.Table:
					if (!seen.Add(v.Table))
					{
						sb.Append("---@type table\n").Append(path).Append(" = nil\n\n");
						return;
					}

					// A class, so that lua-language-server reports fields the table does not have.
					sb.Append("---@class globals.").Append(path).Append('\n').Append(path).Append(" = {}\n\n");

					foreach (var pair in v.Table.Pairs
						.Where(p => p.Key.Type == DataType.String && IsIdentifier(p.Key.String))
						.OrderBy(p => p.Key.String, StringComparer.Ordinal))
					{
						EmitValue(sb, path + "." + pair.Key.String, pair.Value, seen);
					}
					return;
				default:
					sb.Append("---@type ").Append(ValueType(v)).Append('\n').Append(path).Append(" = nil\n\n");
					return;
			}
		}
