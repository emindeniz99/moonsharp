using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace MoonSharp.SourceGenerator
{
	/// <summary>
	/// Writes the C# for a <see cref="TypePlan"/>: one descriptor class per type with one method class and
	/// one field/property class, each dispatching on a member number with a switch, so a type costs
	/// three classes however many members it has. The code is C# 7.3 so every Unity line compiles it.
	/// </summary>
	static class Emitter
	{
		const string MS = "global::MoonSharp.Interpreter.";
		const string MSI = "global::MoonSharp.Interpreter.Interop.";
		const string MSB = "global::MoonSharp.Interpreter.Interop.BasicDescriptors.";
		const string Registry = "global::MoonSharp.Generated.GeneratedUserData.";
		const string Flags = "global::System.Reflection.BindingFlags.Public | global::System.Reflection.BindingFlags.NonPublic | global::System.Reflection.BindingFlags.Instance | global::System.Reflection.BindingFlags.Static | global::System.Reflection.BindingFlags.DeclaredOnly";
		const string Mode = MS + "InteropAccessMode.Default";

		const string Header = "// <auto-generated/>\n// Written by MoonSharp.SourceGenerator; see docs/source-generator.md.\n#pragma warning disable\n";

		public static string EmitType(TypePlan plan, List<TypePlan> all, Helpers helpers, KnownSymbols known)
		{
			string type = Names.Of(plan.Type);
			var w = new StringBuilder();
			w.Append(Header);
			w.Append("namespace MoonSharp.Generated\n{\n");
			w.Append("\tinternal static partial class GeneratedUserData\n\t{\n");
			w.Append("\t\t// The userdata descriptor of ").Append(plan.Type.ToDisplayString()).Append(".\n");
			w.Append("\t\tinternal sealed class ").Append(plan.ClassName).Append(" : ").Append(MSB).Append("DispatchingUserDataDescriptor\n\t\t{\n");
			w.Append("\t\t\tpublic ").Append(plan.ClassName).Append("() : base(typeof(").Append(type).Append("))\n\t\t\t{\n");

			EmitRegistration(w, plan, all);

			w.Append("\t\t\t}\n");

			if (plan.Constructors.Concat(plan.Methods).Any(m => m.Fallback == null))
				EmitMethodClass(w, plan, helpers, known);

			if (plan.Properties.Concat(plan.Fields).Any(v => v.Fallback == null))
				EmitValueClass(w, plan, helpers);

			w.Append("\t\t}\n\t}\n}\n");
			return w.ToString();
		}

		static void EmitRegistration(StringBuilder w, TypePlan plan, List<TypePlan> all)
		{
			string type = Names.Of(plan.Type);

			foreach (MethodPlan m in plan.Constructors)
				w.Append("\t\t\t\tAddMember(\"__new\", ").Append(MethodDescriptor(m, plan)).Append(");\n");

			if (plan.ValueTypeDefaultCtor)
				w.Append("\t\t\t\tAddMember(\"__new\", new ").Append(MSI).Append("ValueTypeDefaultCtorMemberDescriptor(typeof(").Append(type).Append(")));\n");

			foreach (MethodPlan m in plan.Methods)
			{
				if (m.MetaNames.Count == 0)
				{
					w.Append("\t\t\t\tAddMember(").Append(Names.Literal(m.Name)).Append(", ").Append(MethodDescriptor(m, plan)).Append(");\n");
					continue;
				}

				// The same descriptor is also a metamethod, as in StandardUserDataDescriptor.
				w.Append("\t\t\t\t{\n\t\t\t\t\tvar md = ").Append(MethodDescriptor(m, plan)).Append(";\n");
				w.Append("\t\t\t\t\tAddMember(").Append(Names.Literal(m.Name)).Append(", md);\n");
				foreach (string meta in m.MetaNames)
					w.Append("\t\t\t\t\tAddMetaMember(").Append(Names.Literal(meta)).Append(", md);\n");
				w.Append("\t\t\t\t}\n");
			}

			foreach (ValuePlan v in plan.Properties)
				w.Append("\t\t\t\tAddMember(").Append(Names.Literal(v.Name)).Append(", ").Append(ValueDescriptor(v, true)).Append(");\n");

			foreach (ValuePlan v in plan.Fields)
				w.Append("\t\t\t\tAddMember(").Append(Names.Literal(v.Name)).Append(", ").Append(ValueDescriptor(v, false)).Append(");\n");

			foreach (IEventSymbol e in plan.Events)
			{
				w.Append("\t\t\t\tAddMember(").Append(Names.Literal(e.MetadataName)).Append(", ").Append(MSI).Append("EventMemberDescriptor.TryCreateIfVisible(typeof(")
					.Append(Names.Of(e.ContainingType)).Append(").GetEvent(").Append(Names.Literal(e.MetadataName)).Append(", ").Append(Flags).Append("), ").Append(Mode).Append("));\n");
			}

			foreach (NestedPlan n in plan.Nested)
			{
				TypePlan generated = all.FirstOrDefault(p => SymbolEqualityComparer.Default.Equals(p.Type, n.Type));
				string typeOf = TypeOf(n.Type, plan.Type);

				w.Append("\t\t\t\tif (").Append(MS).Append("UserData.RegisterType(");
				if (generated != null)
					w.Append("new ").Append(generated.ClassName).Append("()");
				else
					w.Append(typeOf).Append(", ").Append(Mode).Append(", null");
				w.Append(") != null)\n");
				w.Append("\t\t\t\t\tAddDynValue(").Append(Names.Literal(n.Type.MetadataName)).Append(", ").Append(MS).Append("UserData.CreateStatic(").Append(typeOf).Append("));\n");
			}
		}

		/// <summary>typeof(N), or a reflection lookup when N is not accessible from generated code.</summary>
		static string TypeOf(INamedTypeSymbol nested, INamedTypeSymbol outer)
		{
			if (nested.DeclaredAccessibility == Accessibility.Public || nested.DeclaredAccessibility == Accessibility.Internal || nested.DeclaredAccessibility == Accessibility.ProtectedOrInternal)
				return "typeof(" + Names.Of(nested) + ")";

			return "typeof(" + Names.Of(outer) + ").GetNestedType(" + Names.Literal(nested.MetadataName) + ", global::System.Reflection.BindingFlags.Public | global::System.Reflection.BindingFlags.NonPublic)";
		}

		static string MethodDescriptor(MethodPlan m, TypePlan plan)
		{
			if (m.Fallback != null)
			{
				string declaring = Names.Of(m.Symbol.ContainingType);
				string types = "new global::System.Type[] { " + string.Join(", ", m.Symbol.Parameters.Select(ParameterType)) + " }";
				string lookup = m.IsConstructor
					? "typeof(" + declaring + ").GetConstructor(" + Flags + ", null, " + types + ", null)"
					: "typeof(" + declaring + ").GetMethod(" + Names.Literal(m.Symbol.MetadataName) + ", " + Flags + ", null, " + types + ", null)";
				return "new " + MSI + "MethodMemberDescriptor(" + lookup + ", " + Mode + ")";
			}

			bool isStatic = m.IsConstructor || m.Symbol.IsStatic;
			string name = m.IsConstructor ? ".ctor" : m.Symbol.MetadataName;
			bool ext = IsExtension(m);
			string pars = m.Symbol.Parameters.Length == 0
				? "new " + MSB + "ParameterDescriptor[0]"
				: "new " + MSB + "ParameterDescriptor[] { " + string.Join(", ", m.Symbol.Parameters.Select(ParameterDescriptor)) + " }";

			return "new M(" + m.Id + ", " + Names.Literal(name) + ", " + Bool(isStatic) + ", " + pars + ", " + Bool(ext) + ")";
		}

		static bool IsExtension(MethodPlan m)
		{
			return !m.IsConstructor && m.Symbol.IsExtensionMethod;
		}

		static string ValueDescriptor(ValuePlan v, bool property)
		{
			if (v.Fallback != null)
				return ReflectionValue(v, property);

			string access = MSB + "MemberDescriptorAccess." + (v.CanRead && v.CanWrite ? "CanRead | " + MSB + "MemberDescriptorAccess.CanWrite" : v.CanRead ? "CanRead" : "CanWrite");
			string setFallback = v.SetFallback != null ? ReflectionValue(v, property) : "null";
			return "new V(" + v.Id + ", " + Names.Literal(v.Name) + ", " + Bool(v.IsStatic) + ", " + access + ", " + setFallback + ")";
		}

		static string ReflectionValue(ValuePlan v, bool property)
		{
			string declaring = Names.Of(v.Symbol.ContainingType);
			return property
				? MSI + "PropertyMemberDescriptor.TryCreateIfVisible(typeof(" + declaring + ").GetProperty(" + Names.Literal(v.Name) + ", " + Flags + "), " + Mode + ")"
				: MSI + "FieldMemberDescriptor.TryCreateIfVisible(typeof(" + declaring + ").GetField(" + Names.Literal(v.Name) + ", " + Flags + "), " + Mode + ")";
		}

		static string ParameterType(IParameterSymbol p)
		{
			return "typeof(" + Names.Of(p.Type) + ")" + (p.RefKind != RefKind.None ? ".MakeByRefType()" : "");
		}

		/// <summary>The ParameterDescriptor reflection would build from the ParameterInfo.</summary>
		static string ParameterDescriptor(IParameterSymbol p)
		{
			bool varArgs = p.IsParams && p.Type.TypeKind == TypeKind.Array;
			return "new " + MSB + "ParameterDescriptor(" + Names.Literal(p.MetadataName) + ", " + ParameterType(p) + ", " + Bool(p.IsOptional) + ", null, "
				+ Bool(p.RefKind == RefKind.Out) + ", " + Bool(p.RefKind != RefKind.None) + ", " + Bool(varArgs) + ")";
		}

		static string Bool(bool b)
		{
			return b ? "true" : "false";
		}

		static void EmitMethodClass(StringBuilder w, TypePlan plan, Helpers helpers, KnownSymbols known)
		{
			w.Append(@"
			sealed class M : " + MSI + @"FunctionMemberDescriptorBase
			{
				readonly int m_Id;

				public M(int id, string name, bool isStatic, " + MSB + @"ParameterDescriptor[] parameters, bool isExtensionMethod)
				{
					m_Id = id;
					Initialize(name, isStatic, parameters, isExtensionMethod);
				}

				public override " + MS + "DynValue Execute(" + MS + "Script script, object obj, " + MS + "ScriptExecutionContext context, " + MS + @"CallbackArguments args)
				{
					" + MSB + "MemberDescriptor.CheckAccess(this, " + MSB + @"MemberDescriptorAccess.CanExecute, obj);
					int j = args.IsMethodCall ? 1 : 0;

					switch (m_Id)
					{
");
			foreach (MethodPlan m in plan.Constructors.Concat(plan.Methods))
			{
				if (m.Fallback != null)
					continue;

				w.Append("\t\t\t\t\t\tcase ").Append(m.Id).Append(":\n\t\t\t\t\t\t{\n");

				if (m.Receiver == Receiver.StructAccess)
					w.Append("\t\t\t\t\t\t\treturn ((IStructMembers)obj).Call(").Append(m.StructId).Append(", script, context, args);\n");
				else
					EmitCallBody(w, m, plan, helpers, known, "", "\t\t\t\t\t\t\t");

				w.Append("\t\t\t\t\t\t}\n");
			}

			w.Append(@"					}

					throw new global::System.InvalidOperationException(""no generated member "" + m_Id);
				}
			}
");
		}

		/// <summary>
		/// The body of a generated call: arguments converted as FunctionMemberDescriptorBase.BuildArgumentList
		/// does, the call, and the result (with ref and out values) as BuildReturnValue builds it.
		/// </summary>
		static void EmitCallBody(StringBuilder w, MethodPlan m, TypePlan plan, Helpers helpers, KnownSymbols known, string prefix, string indent)
		{
			IMethodSymbol s = m.Symbol;
			var args = new List<string>();
			var byRef = new List<int>();
			bool ext = IsExtension(m);

			for (int i = 0; i < s.Parameters.Length; i++)
			{
				IParameterSymbol p = s.Parameters[i];
				string local = "a" + i;
				string ptype = Names.Of(p.Type);

				if (p.RefKind != RefKind.None)
					byRef.Add(i);

				if (ext && i == 0)
				{
					w.Append(indent).Append(ptype).Append(" ").Append(local).Append(";\n");
					w.Append(indent).Append("if (obj != null) ").Append(local).Append(" = (").Append(ptype).Append(")obj;\n");
					w.Append(indent).Append("else\n").Append(indent).Append("{\n");
					EmitArgument(w, p, local, helpers, prefix, indent + "\t", false);
					w.Append(indent).Append("}\n");
				}
				else if (KnownSymbols.Is(p.Type, known.Script))
					w.Append(indent).Append(ptype).Append(" ").Append(local).Append(" = script;\n");
				else if (KnownSymbols.Is(p.Type, known.ScriptExecutionContext))
					w.Append(indent).Append(ptype).Append(" ").Append(local).Append(" = context;\n");
				else if (KnownSymbols.Is(p.Type, known.CallbackArguments))
					w.Append(indent).Append(ptype).Append(" ").Append(local).Append(" = args.SkipMethodCall();\n");
				else if (p.RefKind == RefKind.Out)
					w.Append(indent).Append(ptype).Append(" ").Append(local).Append(";\n");
				else if (i == s.Parameters.Length - 1 && p.IsParams && p.Type.TypeKind == TypeKind.Array)
					EmitVarArgs(w, (IArrayTypeSymbol)p.Type, local, helpers, prefix, indent);
				else
					EmitArgument(w, p, local, helpers, prefix, indent, true);

				string modifier = p.RefKind == RefKind.Ref ? "ref " : p.RefKind == RefKind.Out ? "out " : p.RefKind == RefKind.In ? "in " : "";
				args.Add(modifier + local);
			}

			string call = CallExpression(w, m, plan, args, indent);
			bool returnsValue = !m.IsConstructor && s.ReturnsVoid == false;

			if (m.IsConstructor || returnsValue)
				w.Append(indent).Append("var r = ").Append(call).Append(";\n");
			else
				w.Append(indent).Append(call).Append(";\n");

			string result = m.IsConstructor
				? MS + "DynValue.FromObject(script, r)"
				: returnsValue ? helpers.FromClr(s.ReturnType, "r", prefix) : null;

			if (byRef.Count == 0)
			{
				w.Append(indent).Append("return ").Append(result ?? MS + "DynValue.Void").Append(";\n");
				return;
			}

			var parts = new List<string> { result ?? MS + "DynValue.Nil" };
			foreach (int i in byRef)
				parts.Add(helpers.FromClr(s.Parameters[i].Type, "a" + i, prefix));

			w.Append(indent).Append("return ").Append(MS).Append("DynValue.NewTuple(").Append(string.Join(", ", parts)).Append(");\n");
		}

		static void EmitArgument(StringBuilder w, IParameterSymbol p, string local, Helpers helpers, string prefix, string indent, bool declare)
		{
			string ptype = Names.Of(p.Type);
			string v = "v" + local.Substring(1);
			w.Append(indent).Append(MS).Append("DynValue ").Append(v).Append(" = args.RawGet(j++, false) ?? ").Append(MS).Append("DynValue.Void;\n");
			w.Append(indent).Append(declare ? ptype + " " : "").Append(local).Append(" = ");

			string takesDefault = p.IsOptional ? helpers.TakesDefault(p.Type, v, prefix) : null;

			if (takesDefault != null)
				w.Append(takesDefault).Append(" ? ").Append(Literals.Default(p)).Append(" : ");

			w.Append(helpers.ToClr(p.Type, v, prefix)).Append(";\n");
		}

		static void EmitVarArgs(StringBuilder w, IArrayTypeSymbol array, string local, Helpers helpers, string prefix, string indent)
		{
			string elem = Names.Of(array.ElementType);
			string arr = Names.Of(array);
			string n = "n" + local.Substring(1);
			w.Append(indent).Append(arr).Append(" ").Append(local).Append(";\n");
			w.Append(indent).Append("int ").Append(n).Append(" = 0;\n");
			w.Append(indent).Append("while (args.RawGet(j + ").Append(n).Append(", false) != null) ").Append(n).Append("++;\n");
			// A single userdata that already is a matching array is passed as the array itself.
			w.Append(indent).Append(MS).Append("DynValue first").Append(local).Append(" = ").Append(n).Append(" == 1 ? args.RawGet(j, false) : null;\n");
			w.Append(indent).Append("if (first").Append(local).Append(" != null && first").Append(local).Append(".Type == ").Append(MS).Append("DataType.UserData && first")
				.Append(local).Append(".UserData.Object is ").Append(arr).Append(")\n");
			w.Append(indent).Append("\t").Append(local).Append(" = (").Append(arr).Append(")first").Append(local).Append(".UserData.Object;\n");
			w.Append(indent).Append("else\n").Append(indent).Append("{\n");
			w.Append(indent).Append("\t").Append(local).Append(" = new ").Append(ArrayNew(array, n)).Append(";\n");
			w.Append(indent).Append("\tfor (int k = 0; k < ").Append(n).Append("; k++)\n");
			w.Append(indent).Append("\t\t").Append(local).Append("[k] = ").Append(helpers.ToClr(array.ElementType, "args.RawGet(j + k, false)", prefix)).Append(";\n");
			w.Append(indent).Append("}\n");
			w.Append(indent).Append("j += ").Append(n).Append(";\n");
		}

		/// <summary>"T[n]" for T[], and "T[n][]" for T[][] (the size goes on the outermost rank).</summary>
		static string ArrayNew(IArrayTypeSymbol array, string size)
		{
			string elem = Names.Of(array.ElementType);
			int bracket = elem.IndexOf('[');

			if (bracket < 0)
				return elem + "[" + size + "]";

			return elem.Substring(0, bracket) + "[" + size + "]" + elem.Substring(bracket);
		}

		static string CallExpression(StringBuilder w, MethodPlan m, TypePlan plan, List<string> args, string indent)
		{
			IMethodSymbol s = m.Symbol;
			string argList = string.Join(", ", args);

			if (m.IsConstructor)
				return "new " + Names.Of(plan.Type) + "(" + argList + ")";

			string recv;

			switch (m.Receiver)
			{
				case Receiver.Static:
					recv = Names.Of(s.ContainingType);
					break;
				case Receiver.Copy:
					w.Append(indent).Append(Names.Of(m.ReceiverType)).Append(" self = (").Append(Names.Of(m.ReceiverType)).Append(")obj;\n");
					recv = "self";
					break;
				case Receiver.StructAccess:
					recv = "this";
					break;
				default:
					recv = "((" + Names.Of(m.ReceiverType) + ")obj)";
					break;
			}

			switch (s.MethodKind)
			{
				case MethodKind.PropertyGet:
				{
					var prop = (IPropertySymbol)s.AssociatedSymbol;
					return prop.IsIndexer ? recv + "[" + argList + "]" : recv + "." + Names.Escape(prop.Name);
				}
				case MethodKind.PropertySet:
				{
					var prop = (IPropertySymbol)s.AssociatedSymbol;
					string value = args[args.Count - 1];
					string target = prop.IsIndexer ? recv + "[" + string.Join(", ", args.Take(args.Count - 1)) + "]" : recv + "." + Names.Escape(prop.Name);
					return target + " = " + value;
				}
				case MethodKind.EventAdd:
					return recv + "." + Names.Escape(((IEventSymbol)s.AssociatedSymbol).Name) + " += " + args[0];
				case MethodKind.EventRemove:
					return recv + "." + Names.Escape(((IEventSymbol)s.AssociatedSymbol).Name) + " -= " + args[0];
				case MethodKind.UserDefinedOperator:
					return string.Format(Names.OperatorSyntax(s.MetadataName, args.Count), args.ToArray());
				case MethodKind.Conversion:
					return "(" + Names.Of(s.ReturnType) + ")(" + args[0] + ")";
				default:
					return recv + "." + Names.Escape(s.Name) + "(" + argList + ")";
			}
		}

		static void EmitValueClass(StringBuilder w, TypePlan plan, Helpers helpers)
		{
			w.Append(@"
			sealed class V : " + MSB + @"IMemberDescriptor
			{
				readonly int m_Id;
				readonly " + MSB + @"MemberDescriptorAccess m_Access;
				readonly " + MSB + @"IMemberDescriptor m_SetFallback;

				public V(int id, string name, bool isStatic, " + MSB + "MemberDescriptorAccess access, " + MSB + @"IMemberDescriptor setFallback)
				{
					m_Id = id;
					Name = name;
					IsStatic = isStatic;
					m_Access = access;
					m_SetFallback = setFallback;
				}

				public bool IsStatic { get; private set; }
				public string Name { get; private set; }
				public " + MSB + @"MemberDescriptorAccess MemberAccess { get { return m_Access; } }

				public " + MS + "DynValue GetValue(" + MS + @"Script script, object obj)
				{
					" + MSB + "MemberDescriptor.CheckAccess(this, " + MSB + @"MemberDescriptorAccess.CanRead, obj);

					switch (m_Id)
					{
");
			foreach (ValuePlan v in plan.Properties.Concat(plan.Fields))
			{
				if (v.Fallback != null || !v.CanRead)
					continue;

				w.Append("\t\t\t\t\t\tcase ").Append(v.Id).Append(":\n");

				if (v.GetReceiver == Receiver.StructAccess)
					w.Append("\t\t\t\t\t\t\treturn ((IStructMembers)obj).Get(").Append(v.StructGetId).Append(", script);\n");
				else
					w.Append("\t\t\t\t\t\t\treturn ").Append(helpers.FromClr(v.ValueType, ValueTarget(v, v.GetReceiver, plan), "")).Append(";\n");
			}

			w.Append(@"					}

					throw new global::System.InvalidOperationException(""no generated member "" + m_Id);
				}

				public void SetValue(" + MS + "Script script, object obj, " + MS + @"DynValue value)
				{
					" + MSB + "MemberDescriptor.CheckAccess(this, " + MSB + @"MemberDescriptorAccess.CanWrite, obj);

					if (m_SetFallback != null)
					{
						m_SetFallback.SetValue(script, obj, value);
						return;
					}

					switch (m_Id)
					{
");
			foreach (ValuePlan v in plan.Properties.Concat(plan.Fields))
			{
				if (v.Fallback != null || !v.CanWrite || v.SetFallback != null)
					continue;

				w.Append("\t\t\t\t\t\tcase ").Append(v.Id).Append(":\n");

				if (v.SetReceiver == Receiver.StructAccess)
					w.Append("\t\t\t\t\t\t\t((IStructMembers)obj).Set(").Append(v.StructSetId).Append(", script, value);\n");
				else
					w.Append("\t\t\t\t\t\t\t").Append(ValueTarget(v, v.SetReceiver, plan)).Append(" = ").Append(helpers.ToClr(v.ValueType, "value", "")).Append(";\n");

				w.Append("\t\t\t\t\t\t\treturn;\n");
			}

			w.Append(@"					}

					throw new global::System.InvalidOperationException(""no generated member "" + m_Id);
				}
			}
");
		}

		static string ValueTarget(ValuePlan v, Receiver receiver, TypePlan plan)
		{
			string name = Names.Escape(v.Symbol.Name);

			switch (receiver)
			{
				case Receiver.Static:
					return Names.Of(v.Symbol.ContainingType) + "." + name;
				case Receiver.StructAccess:
					return "this." + name;
				default:
					// Reference for classes; for structs a copy, read only.
					return "((" + Names.Of(v.ReceiverType) + ")obj)." + name;
			}
		}

		/// <summary>
		/// The partial declaration of a partial struct that implements GeneratedUserData.IStructMembers, so
		/// the descriptor reaches the struct inside its box and changes it in place, as reflection does.
		/// </summary>
		public static string EmitStructPartial(TypePlan plan, Helpers helpers, KnownSymbols known)
		{
			var w = new StringBuilder();
			w.Append(Header);

			var containers = new List<INamedTypeSymbol>();
			for (INamedTypeSymbol t = plan.Type; t != null; t = t.ContainingType)
				containers.Insert(0, t);

			string ns = plan.Type.ContainingNamespace == null || plan.Type.ContainingNamespace.IsGlobalNamespace ? null : plan.Type.ContainingNamespace.ToDisplayString();
			string indent = "";

			if (ns != null)
			{
				w.Append("namespace ").Append(ns).Append("\n{\n");
				indent = "\t";
			}

			for (int i = 0; i < containers.Count; i++)
			{
				INamedTypeSymbol t = containers[i];
				bool last = i == containers.Count - 1;
				w.Append(indent).Append("partial ").Append(t.TypeKind == TypeKind.Struct ? "struct " : "class ").Append(t.Name);
				if (t.TypeParameters.Length > 0)
					w.Append("<").Append(string.Join(", ", t.TypeParameters.Select(tp => tp.Name))).Append(">");
				if (last)
					w.Append(" : ").Append(Registry).Append("IStructMembers");
				w.Append("\n").Append(indent).Append("{\n");
				indent += "\t";
			}

			string sig = MS + "DynValue " + Registry + "IStructMembers.";

			// Calls
			w.Append(indent).Append(sig).Append("Call(int id, ").Append(MS).Append("Script script, ").Append(MS).Append("ScriptExecutionContext context, ").Append(MS).Append("CallbackArguments args)\n");
			w.Append(indent).Append("{\n");
			w.Append(indent).Append("\tint j = args.IsMethodCall ? 1 : 0;\n");
			w.Append(indent).Append("\tswitch (id)\n").Append(indent).Append("\t{\n");
			foreach (MethodPlan m in plan.Constructors.Concat(plan.Methods))
			{
				if (m.Fallback != null || m.StructId < 0)
					continue;
				w.Append(indent).Append("\t\tcase ").Append(m.StructId).Append(":\n").Append(indent).Append("\t\t{\n");
				EmitCallBody(w, m, plan, helpers, known, Registry, indent + "\t\t\t");
				w.Append(indent).Append("\t\t}\n");
			}
			w.Append(indent).Append("\t}\n");
			w.Append(indent).Append("\tthrow new global::System.InvalidOperationException(\"no generated member \" + id);\n");
			w.Append(indent).Append("}\n\n");

			// Reads
			w.Append(indent).Append(sig).Append("Get(int id, ").Append(MS).Append("Script script)\n");
			w.Append(indent).Append("{\n").Append(indent).Append("\tswitch (id)\n").Append(indent).Append("\t{\n");
			foreach (ValuePlan v in plan.Properties.Concat(plan.Fields))
			{
				if (v.Fallback != null || v.StructGetId < 0)
					continue;
				w.Append(indent).Append("\t\tcase ").Append(v.StructGetId).Append(": return ")
					.Append(helpers.FromClr(v.ValueType, "this." + Names.Escape(v.Symbol.Name), Registry)).Append(";\n");
			}
			w.Append(indent).Append("\t}\n");
			w.Append(indent).Append("\tthrow new global::System.InvalidOperationException(\"no generated member \" + id);\n");
			w.Append(indent).Append("}\n\n");

			// Writes
			w.Append(indent).Append("void ").Append(Registry).Append("IStructMembers.Set(int id, ").Append(MS).Append("Script script, ").Append(MS).Append("DynValue value)\n");
			w.Append(indent).Append("{\n").Append(indent).Append("\tswitch (id)\n").Append(indent).Append("\t{\n");
			foreach (ValuePlan v in plan.Properties.Concat(plan.Fields))
			{
				if (v.Fallback != null || v.StructSetId < 0)
					continue;
				w.Append(indent).Append("\t\tcase ").Append(v.StructSetId).Append(": this.").Append(Names.Escape(v.Symbol.Name)).Append(" = ")
					.Append(helpers.ToClr(v.ValueType, "value", Registry)).Append("; return;\n");
			}
			w.Append(indent).Append("\t}\n");
			w.Append(indent).Append("\tthrow new global::System.InvalidOperationException(\"no generated member \" + id);\n");
			w.Append(indent).Append("}\n");

			for (int i = containers.Count - 1; i >= 0; i--)
			{
				indent = indent.Substring(1);
				w.Append(indent).Append("}\n");
			}

			if (ns != null)
				w.Append("}\n");

			return w.ToString();
		}

